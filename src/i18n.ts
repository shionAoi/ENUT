export type Lang = 'en' | 'es';

export function resolveLang(saved: string | null): Lang {
  return saved === 'es' ? 'es' : 'en';
}

export function saveLang(storage: Pick<Storage, 'setItem'>, lang: Lang): void {
  try {
    storage.setItem('ai-monitor-lang', lang);
  } catch {
    /* Storage may be unavailable in a webview. */
  }
}

